// OpenUI Lang 1.0 export: one program per screen and variant for @openuidev/react-ui. One
// `identifier = Expression` statement per line, `root` first, then each element in source order (forward
// references are allowed); positional arguments in the schema's order, null for a skipped optional,
// trailing nulls dropped. lang-core skips `//` to the end of a line (checked against its parser), so each
// file opens with a comment naming the screen and an element's note follows its statement as a comment.
// Statement names come from element ids: lang-core reads an identifier as ASCII letters, digits and `_`
// starting with a lowercase letter or `_` (an uppercase start is a component name), and true/false/null
// are literals, so those are renamed.
import { OPENUI_SCHEMA } from './openui-schema.js';
import { call, commentText } from './openui-lit.js';
import { mapNode } from './openui-map.js';
import { screenFiles, notesOf } from './files.js';

const RESERVED = new Set(['root', 'true', 'false', 'null']);

function ident(id, used) {
  let base = String(id).replace(/[^A-Za-z0-9_]/g, '_');
  if (!/^[a-z_]/.test(base)) base = `_${base}`;
  if (RESERVED.has(base)) base += '_el';
  let name = base;
  for (let i = 2; used.has(name); i++) name = `${base}_${i}`;
  used.add(name);
  return name;
}

const comment = (note) => (note && commentText(note) ? ` // ${commentText(note)}` : '');

function program(screen, labels) {
  const used = new Set(['root']);
  const lines = [];
  const ctx = { labels, emit: null };
  ctx.emit = (node) => {
    const id = node === screen.root ? 'root' : ident(node.id, used);
    const at = lines.push(null) - 1; // reserve the line so a parent precedes its children
    const m = mapNode(node, ctx);
    if (!m) return null;
    lines[at] = `${id} = ${call(m.component, m.props)}${comment(node.note)}`;
    return { $ref: id, component: m.component };
  };
  ctx.emit(screen.root);
  const head = `// ${commentText(screen.label || screen.id)}: generated by wiremark from a wireframe for @openuidev/react-ui ${OPENUI_SCHEMA.version}. A starting point, not a design.`;
  return [head, ...lines.filter((l) => l !== null)].join('\n') + '\n';
}

export function toOpenUI(body, info) {
  const r = screenFiles(body, info);
  if (!r.ok) return r;
  const labels = new Map(r.mock.screens.map((s) => [s.id, s.label || s.id]));
  return {
    ok: true,
    files: r.screens.map(({ screen, name }) => ({
      screen: screen.variantOf ?? screen.id,
      variant: screen.variantOf ? screen.id : null,
      name,
      text: program(screen, labels),
      notes: notesOf(screen.root),
    })),
  };
}
