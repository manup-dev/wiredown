// Builds icons.js from lucide-static@1.72.0: node build.mjs [path to the unpacked package]
// (default node_modules/lucide-static). Each svg becomes one path-data string through the library's
// svgToPath and explicitPath; an icon the pack format refuses is skipped and counted.
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { svgToPath } from '../../scripts/svg-to-path.mjs';
import { explicitPath } from '../../scripts/path-normalize.mjs';
import { defineIconPack } from '../../src/packs-define.js';

const here = fileURLToPath(new URL('.', import.meta.url));
const root = process.argv[2] ?? join(here, 'node_modules', 'lucide-static');
const dir = join(root, 'icons');
const icons = {};
const skipped = [];
for (const f of readdirSync(dir).filter((n) => n.endsWith('.svg')).sort()) {
  const name = f.slice(0, -4);
  try {
    const svg = readFileSync(join(dir, f), 'utf8');
    const d = explicitPath(svgToPath(svg));
    defineIconPack({ id: 'check', name: 'check', version: '0', icons: { [name]: d } });
    icons[name] = d;
  } catch (e) {
    skipped.push(`${name}: ${e.message}`);
  }
}
const header = `// Generated by build.mjs from lucide-static@1.72.0 (ISC); do not edit.
// One line per icon, so this file is long on purpose (the 300-line rule is for the library's src/).
`;
const body = Object.entries(icons).map(([n, d]) => `${JSON.stringify(n)}: ${JSON.stringify(d)},`).join('\n');
writeFileSync(join(here, 'icons.js'), `${header}export default {\n${body}\n};\n`);
console.log(`lucide: ${Object.keys(icons).length} icons, ${skipped.length} skipped`);
for (const s of skipped) console.log(`  skipped ${s}`);
