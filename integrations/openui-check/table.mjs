// Turns @openuidev/react-ui's own `openuiLibrary.toJSONSchema()` into the plain table the wiremark core reads.
// Shared by gen-schema.mjs (writes the table) and check.test.mjs (fails when the committed table is stale).
import { readFileSync } from 'node:fs'

export const versionOf = (pkg) =>
  JSON.parse(readFileSync(new URL(`./node_modules/${pkg}/package.json`, import.meta.url), 'utf8')).version

export async function loadLibrary() {
  const ui = await import('@openuidev/react-ui/genui-lib')
  const lib = ui.openuiLibrary
  return { root: lib.root, schema: lib.toJSONSchema() }
}

const refName = (s) => (s && typeof s.$ref === 'string' ? s.$ref.split('/').pop() : null)

// The component names an array argument's items may be, or null when any value is allowed.
function slotOf(prop, components) {
  const items = prop.items
  if (!items) return null
  const refs = items.anyOf ? items.anyOf.map(refName) : [refName(items)]
  if (refs.some((r) => !r || !components.has(r))) return null
  return refs
}

function typeOf(prop, components) {
  const ref = refName(prop)
  if (ref) return components.has(ref) ? 'component' : ref === 'ActionExpression' ? 'action' : 'any'
  if (prop.anyOf) return prop.anyOf.every((a) => components.has(refName(a))) ? 'component' : 'any'
  return typeof prop.type === 'string' ? prop.type : 'any'
}

/** One row per component: positional args (the schema's property order), required, types, enums, slots. */
export function buildTable(schema, root, version, langCore) {
  // `properties` holds the component names; other `$defs` entries are data shapes (lang-core LibraryJSONSchema).
  const names = Object.keys(schema.properties ?? {})
  const components = new Set(names)
  const out = {}
  for (const name of names) {
    const def = schema.$defs[name]
    const props = def.properties ?? {}
    const row = { args: Object.keys(props), required: def.required ?? [], types: {} }
    for (const [arg, p] of Object.entries(props)) {
      row.types[arg] = typeOf(p, components)
      if (Array.isArray(p.enum)) (row.enums ??= {})[arg] = p.enum
      const slot = row.types[arg] === 'array' ? slotOf(p, components) : null
      if (slot) (row.slots ??= {})[arg] = slot
    }
    out[name] = row
  }
  return { version, langCore, root, components: out }
}

/** The committed core module, one line per component so it stays inside the 300-line budget. */
export function tableModule(table) {
  const rows = Object.entries(table.components).map(([n, r]) => `    ${JSON.stringify(n)}: ${JSON.stringify(r)},`)
  return [
    `// GENERATED by integrations/openui-check/gen-schema.mjs from @openuidev/react-ui ${table.version}`,
    `// (openuiLibrary.toJSONSchema(), parsed by @openuidev/lang-core ${table.langCore}). Do not edit by hand.`,
    '// args = positional order; types: string|number|boolean|array|object|component|action|any;',
    '// slots = the component names an array argument accepts (absent = anything).',
    'export const OPENUI_SCHEMA = Object.freeze({',
    `  version: ${JSON.stringify(table.version)},`,
    `  langCore: ${JSON.stringify(table.langCore)},`,
    `  root: ${JSON.stringify(table.root)},`,
    '  components: Object.freeze({',
    ...rows,
    '  }),',
    '});',
    '',
  ].join('\n')
}
