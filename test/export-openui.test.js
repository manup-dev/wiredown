test('only components the schema knows, and the one action form', () => {
  const known = new Set(Object.keys(OPENUI_SCHEMA.components))
  for (const body of [login, all])
    for (const f of toOpenUI(body).files)
      for (const line of statements(f)) {
        const code = line.replace(/"(?:[^"\\]|\\.)*"/g, '""').replace(/ \/\/ .*$/, '')
        for (const m of code.matchAll(/(@?)\b([A-Z][A-Za-z]*)\(/g)) assert.ok(m[1] ? m[2] === 'ToAssistant' : known.has(m[2]), m[2])
      }
})

test('strings are escaped; author text cannot break a statement', () => {
  const r = toOpenUI('button "a\\"b // c # d \\\\ e" #x note="one // two"\ntext "line\\nbreak \u2028 end \u{1F600}"')
  assert.equal(r.ok, true)
  const text = r.files[0].text
  const lines = text.trim().split('\n')
  assert.ok(lines.every((l) => l.startsWith('//') || /^[a-z_][A-Za-z0-9_]* = /.test(l)), text)
  assert.ok(text.includes('x = Button("a\\"b // c # d \\\\ e") // one // two\n'), text)
  assert.ok(text.includes('TextContent("line\\\\nbreak \\u2028 end \u{1F600}")'), text)
  assert.ok(!/[\u2028\u2029]/.test(text))
})

test('a comment line cannot carry a line break', () => {
  const r = toOpenUI('screen s "a\u2028b"\n  button "x" note="n\u2029m"')
  assert.equal(r.ok, true)
  assert.ok(!/[\r\u2028\u2029]/.test(r.files[0].text))
})

test('identifiers are safe whatever the element id', () => {
  const r = toOpenUI('button "a" #root\nbutton "b" #null\nbutton "c" #true\nbutton "d" #my-button\nbutton "e" #root-el')
  assert.equal(r.ok, true)
  const ids = statements(r.files[0]).map((l) => l.split(' = ')[0])
  assert.deepEqual(ids.slice(1), ['root_el', 'null_el', 'true_el', 'my_button', 'root_el_2'])
})

test('refuses a block with errors; deterministic and linear', () => {
  assert.equal(toOpenUI('gadget "x"').ok, false)
  assert.equal(toOpenUI(kinds).ok, false)
  assert.equal(JSON.stringify(toOpenUI(all)), JSON.stringify(toOpenUI(all)))
  const big = 'stack\n' + '  button "x"\n'.repeat(1400)
  const t = performance.now(); toOpenUI(big); assert.ok(performance.now() - t < 300)
})

test('names that live on Object.prototype are plain names, never prototype values', () => {
  for (const name of ['constructor', '__proto__', 'toString', 'hasOwnProperty', 'valueOf']) {
    for (const [body, re] of [
      [`icon #i1 icon=${name}`, new RegExp(`i1 = Icon\\("${name}"\\)`)],
      [`badge "B" icon=${name}`, new RegExp(`Tag\\("B", Icon\\("${name}"\\)\\)`)],
      [`button #b1 icon=${name}`, new RegExp(`b1 = IconButton\\("b1", Icon\\("${name}"\\)\\)`)],
    ]) {
      const r = toOpenUI(body)
      assert.equal(r.ok, true, body)
      assert.match(r.files[0].text, re, body)
      assert.ok(!r.files[0].text.includes('{}'), body)
    }
  }
})

test('trailing nulls are trimmed only after the last required argument', async () => {
  const { renderArgs } = await import('../src/export/openui-lit.js')
  const spec = { args: ['a', 'b', 'c', 'd'], required: ['c'], types: { a: 'string', b: 'string', c: 'component', d: 'string' } }
  assert.deepEqual(renderArgs(spec, { a: 'x' }), ['"x"', 'null', 'null'])
  assert.deepEqual(renderArgs(spec, {}), ['null', 'null', 'null'])
  assert.deepEqual(renderArgs({ ...spec, required: [] }, { a: 'x' }), ['"x"'])
  assert.deepEqual(renderArgs(spec, { a: 'x', d: 'y' }), ['"x"', 'null', 'null', '"y"'])
})
